VALID_STATE_CODES = frozenset(STATE_CODES.values())


def phone(value: str) -> str:
    raw = value.strip()
    digits = re.sub(r"\D", "", raw)
    if len(digits) == 10:
        return "+1" + digits
    if len(digits) == 11 and digits.startswith("1"):
        return "+" + digits
    if raw.startswith("+") and 8 <= len(digits) <= 15:
        return "+" + digits
    raise ValueError("INVALID_PHONE")


def state(value: str) -> str:
    normalized = " ".join(value.strip().upper().replace(".", "").split())
    if normalized in VALID_STATE_CODES:
        return normalized
    if normalized in STATE_CODES:
        return STATE_CODES[normalized]
    raise ValueError("INVALID_STATE")


def postal_code(value: str) -> str:
    value = value.strip()
    if not re.fullmatch(r"\d{5}(?:-\d{4})?", value):
        raise ValueError("INVALID_POSTAL_CODE")
    return value


def email(value: str) -> str:
    value = value.strip().lower()
    if not re.fullmatch(r"[^\s@]+@[^\s@]+\.[^\s@]+", value):
        raise ValueError("INVALID_EMAIL")
    return value
